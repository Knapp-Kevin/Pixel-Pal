import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const coreManifestPath = resolve('art/production-manifest.json');
const manifestPath = resolve('art/adventure-production-manifest.json');
const outputPath = resolve('apps/tablet/src/generatedProductionArtRegistry.ts');
const checkOnly = process.argv.includes('--check');

const allowedStatuses = new Set(['planned', 'benchmark', 'approved', 'production']);

function fail(message) {
  throw new Error(`Production art registry generation failed: ${message}`);
}

function requireString(value, label) {
  if (typeof value !== 'string' || value.trim().length === 0) fail(`${label} must be a non-empty string.`);
  return value;
}

function publicUrl(runtimePath, label) {
  const path = requireString(runtimePath, label).replaceAll('\\', '/');
  const prefix = 'apps/tablet/public/';
  if (!path.startsWith(prefix)) fail(`${label} must live under ${prefix}.`);
  return `/${path.slice(prefix.length)}`;
}

function humanize(value) {
  return value
    .split('-')
    .map((part) => part.length > 0 ? `${part[0].toUpperCase()}${part.slice(1)}` : part)
    .join(' ');
}

function quote(value) {
  return JSON.stringify(value);
}

function registrySource(sceneAssets, releaseBlockerCount) {
  const serializedScenes = sceneAssets.length === 0
    ? '[]'
    : `[
 ${sceneAssets.map((asset) => `    {
      id: ${quote(asset.id)},
      status: ${quote(asset.status)},
      src: ${quote(asset.src)},
      width: ${asset.width},
      height: ${asset.height},
      portraitSrc: ${quote(asset.portraitSrc)},
      portraitWidth: ${asset.portraitWidth},
      portraitHeight: ${asset.portraitHeight},
      sceneId: ${quote(asset.sceneId)},
      variant: ${quote(asset.variant)},
      alt: ${quote(asset.alt)},
      objectPosition: ${quote(asset.objectPosition)},
      portraitObjectPosition: ${quote(asset.portraitObjectPosition)}
    }`).join(',\n')}
  ]`;

  return `// Generated by scripts/generate-production-art-registry.mjs.
// Do not edit by hand. Update the production art manifests and regenerate.

import type { ProductionArtRegistry } from '@pixel-pals/renderer';

export const generatedProductionArtRegistry: ProductionArtRegistry = {
  palAssets: [],
  sceneAssets: ${serializedScenes}
};

export const generatedProductionArtRelease = {
  ready: ${releaseBlockerCount === 0},
  blockerCount: ${releaseBlockerCount}
} as const;
`;
}

const coreManifest = JSON.parse(await readFile(coreManifestPath, 'utf8'));
if (coreManifest.schemaVersion !== 1 || coreManifest.product !== 'Pixel Pals' || !Array.isArray(coreManifest.assets)) {
  fail('production-manifest.json must be a Pixel Pals schemaVersion 1 manifest.');
}

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
if (manifest.schemaVersion !== 2 || manifest.product !== 'Pixel Pals' || !Array.isArray(manifest.assets)) {
  fail('adventure-production-manifest.json must be a Pixel Pals schemaVersion 2 manifest.');
}

let releaseBlockerCount = coreManifest.assets.filter(
  (asset) => asset.releaseRequired === true && asset.status !== 'production'
).length;

const sceneAssets = [];
for (const asset of manifest.assets) {
  requireString(asset.id, 'asset.id');
  requireString(asset.subject, `${asset.id}.subject`);
  requireString(asset.sceneId, `${asset.id}.sceneId`);
  if (!Array.isArray(asset.views)) fail(`${asset.id}.views must be an array.`);

  const variants = new Map();
  for (const view of asset.views) {
    requireString(view.id, `${asset.id}.view.id`);
    const variant = requireString(view.variant, `${asset.id}.${view.id}.variant`);
    const orientation = requireString(view.orientation, `${asset.id}.${view.id}.orientation`);
    if (orientation !== 'landscape' && orientation !== 'portrait') {
      fail(`${asset.id}.${view.id}.orientation must be landscape or portrait.`);
    }
    if (!allowedStatuses.has(view.status)) fail(`${asset.id}.${view.id} has unsupported status ${view.status}.`);
    if (asset.releaseRequired === true && view.status !== 'production') releaseBlockerCount += 1;
    const pair = variants.get(variant) ?? {};
    if (pair[orientation]) fail(`${asset.id}.${variant} has duplicate ${orientation} views.`);
    pair[orientation] = view;
    variants.set(variant, pair);
  }

  for (const [variant, pair] of variants) {
    if (!pair.landscape || !pair.portrait) fail(`${asset.id}.${variant} requires landscape and portrait views.`);
    const landscapeActive = pair.landscape.status !== 'planned';
    const portraitActive = pair.portrait.status !== 'planned';
    if (!landscapeActive && !portraitActive) continue;
    if (landscapeActive !== portraitActive) {
      fail(`${asset.id}.${variant} must promote landscape and portrait together.`);
    }
    if (pair.landscape.status !== pair.portrait.status) {
      fail(`${asset.id}.${variant} landscape and portrait statuses must match.`);
    }

    sceneAssets.push({
      id: `${asset.id}-${variant}`,
      status: pair.landscape.status,
      src: publicUrl(pair.landscape.runtimePath, `${asset.id}.${pair.landscape.id}.runtimePath`),
      width: pair.landscape.width,
      height: pair.landscape.height,
      portraitSrc: publicUrl(pair.portrait.runtimePath, `${asset.id}.${pair.portrait.id}.runtimePath`),
      portraitWidth: pair.portrait.width,
      portraitHeight: pair.portrait.height,
      sceneId: asset.sceneId,
      variant,
      alt: pair.landscape.alt ?? `${asset.subject}: ${humanize(variant)}`,
      objectPosition: pair.landscape.objectPosition ?? '50% 50%',
      portraitObjectPosition: pair.portrait.objectPosition ?? '50% 50%'
    });
  }
}

sceneAssets.sort((left, right) => left.id.localeCompare(right.id));
const source = registrySource(sceneAssets, releaseBlockerCount);

if (checkOnly) {
  const existing = await readFile(outputPath, 'utf8').catch(() => null);
  if (existing !== source) {
    fail('generatedProductionArtRegistry.ts is out of date. Run npm run generate:art-registry.');
  }
  console.log(`Production art registry is current: ${sceneAssets.length} responsive scene assets, ${releaseBlockerCount} release blockers.`);
} else {
  await writeFile(outputPath, source, 'utf8');
  console.log(`Generated ${sceneAssets.length} responsive scene assets and ${releaseBlockerCount} release blockers at ${outputPath}.`);
}
